-- Storage path format used by the application:
-- <base64url(stageId)>/<base64url(gradeMetaKey)>.xlsx
CREATE OR REPLACE FUNCTION public.storage_path_stage_id(object_name text)
RETURNS text
LANGUAGE plpgsql IMMUTABLE SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  token text;
  padded text;
BEGIN
  token := split_part(COALESCE(object_name,''), '/', 1);
  IF token = '' THEN RETURN NULL; END IF;
  token := replace(replace(token, '-', '+'), '_', '/');
  padded := token || CASE mod(length(token), 4)
    WHEN 2 THEN '=='
    WHEN 3 THEN '='
    WHEN 0 THEN ''
    ELSE ''
  END;
  BEGIN
    RETURN convert_from(decode(padded, 'base64'), 'UTF8');
  EXCEPTION WHEN others THEN
    RETURN NULL;
  END;
END;
$$;

CREATE OR REPLACE FUNCTION public.can_access_storage_object(object_name text)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public
AS $$
  SELECT public.is_superadmin()
    OR EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid()
        AND p.is_active IS DISTINCT FROM false
        AND jsonb_typeof(p.stage_ids) = 'array'
        AND p.stage_ids ? public.storage_path_stage_id(object_name)
    );
$$;

